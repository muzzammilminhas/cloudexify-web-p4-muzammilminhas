create extension if not exists pgcrypto;

do $$ begin
  create type public.user_role as enum ('customer', 'admin');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.order_status as enum ('Pending', 'Preparing', 'Ready');
exception when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(trim(full_name)) between 2 and 80),
  role public.user_role not null default 'customer',
  created_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(trim(name)) between 2 and 80),
  description text not null check (char_length(trim(description)) between 10 and 280),
  price numeric(10,2) not null check (price between 50 and 100000),
  category text not null check (category in ('From the Angaar', 'Potohar Plates', 'Rice & Dum', 'Garden & Grain', 'Meetha', 'House Pour')),
  image_url text not null default 'assets/menu-atlas.webp' check (char_length(image_url) <= 500),
  image_position text not null default 'center' check (image_position in ('top-left', 'top-right', 'bottom-left', 'bottom-right', 'center')),
  badge text check (badge is null or char_length(badge) <= 30),
  spice_level smallint not null default 0 check (spice_level between 0 and 3),
  dietary text check (dietary is null or char_length(dietary) <= 40),
  available boolean not null default true,
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated always as identity unique,
  user_id uuid not null references public.profiles(id) on delete restrict,
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 25),
  total numeric(12,2) not null check (total > 0),
  status public.order_status not null default 'Pending',
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  preparing_at timestamptz,
  ready_at timestamptz,
  constraint orders_user_idempotency_unique unique (user_id, idempotency_key),
  constraint orders_status_timestamps_check check (
    (status = 'Pending' and preparing_at is null and ready_at is null)
    or (status = 'Preparing' and preparing_at is not null and ready_at is null)
    or (status = 'Ready' and preparing_at is not null and ready_at is not null)
  )
);

create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists orders_status_created_idx on public.orders(status, created_at desc);
create index if not exists menu_items_available_category_idx on public.menu_items(available, category);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists menu_items_touch_updated_at on public.menu_items;
create trigger menu_items_touch_updated_at
before update on public.menu_items
for each row execute function public.touch_updated_at();

drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at
before update on public.orders
for each row execute function public.touch_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text;
begin
  v_name := trim(coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  if char_length(v_name) < 2 then
    v_name := split_part(coalesce(new.email, 'Guest'), '@', 1);
  end if;
  v_name := left(v_name, 80);

  insert into public.profiles (id, full_name, role)
  values (new.id, v_name, 'customer')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

