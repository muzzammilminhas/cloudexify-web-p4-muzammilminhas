create or replace function public.place_order(p_cart jsonb, p_idempotency_key uuid)
returns table (
  order_id uuid,
  order_number bigint,
  total numeric,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_raw_count integer;
  v_expected_count integer;
  v_matched_count integer;
  v_quantities_valid boolean;
  v_items jsonb;
  v_total numeric(12,2);
begin
  if v_user_id is null then
    raise exception 'Sign in before placing an order.' using errcode = '42501';
  end if;
  if p_idempotency_key is null then
    raise exception 'A checkout reference is required.' using errcode = '22023';
  end if;

  return query
  select o.id, o.order_number, o.total, o.status::text, o.created_at
  from public.orders o
  where o.user_id = v_user_id and o.idempotency_key = p_idempotency_key;
  if found then return; end if;

  if p_cart is null or jsonb_typeof(p_cart) <> 'array' then
    raise exception 'The cart format is invalid.' using errcode = '22023';
  end if;
  select count(*) into v_raw_count from jsonb_array_elements(p_cart);
  if v_raw_count < 1 or v_raw_count > 25 then
    raise exception 'Choose between 1 and 25 distinct cart lines.' using errcode = '22023';
  end if;

  with requested as (
    select item_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_cart) as line(item_id bigint, quantity integer)
    group by item_id
  )
  select count(*), coalesce(bool_and(item_id is not null and quantity between 1 and 20), false)
  into v_expected_count, v_quantities_valid
  from requested;

  if not v_quantities_valid then
    raise exception 'Each dish quantity must be between 1 and 20.' using errcode = '22023';
  end if;

  with requested as (
    select item_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_cart) as line(item_id bigint, quantity integer)
    group by item_id
  ), validated as (
    select m.id, m.name, m.price, r.quantity
    from requested r
    join public.menu_items m on m.id = r.item_id
    where m.available = true
    for share of m
  )
  select
    count(*),
    jsonb_agg(
      jsonb_build_object(
        'menu_item_id', id,
        'name', name,
        'unit_price', price,
        'quantity', quantity,
        'line_total', price * quantity
      ) order by name
    ),
    sum(price * quantity)
  into v_matched_count, v_items, v_total
  from validated;

  if v_matched_count <> v_expected_count then
    raise exception 'One or more dishes are unavailable. Refresh the menu and try again.' using errcode = '22023';
  end if;

  insert into public.orders (user_id, items, total, idempotency_key)
  values (v_user_id, v_items, v_total, p_idempotency_key);

  return query
  select o.id, o.order_number, o.total, o.status::text, o.created_at
  from public.orders o
  where o.user_id = v_user_id and o.idempotency_key = p_idempotency_key;
end;
$$;

revoke all on function public.place_order(jsonb, uuid) from public, anon;
grant execute on function public.place_order(jsonb, uuid) to authenticated;

create or replace function public.admin_update_order_status(p_order_id uuid, p_new_status text)
returns table (
  order_id uuid,
  order_number bigint,
  status text,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current public.order_status;
begin
  if not public.is_admin() then
    raise exception 'Admin permission is required.' using errcode = '42501';
  end if;
  if p_new_status not in ('Pending', 'Preparing', 'Ready') then
    raise exception 'The requested order status is invalid.' using errcode = '22023';
  end if;

  select o.status into v_current
  from public.orders o
  where o.id = p_order_id
  for update;
  if not found then
    raise exception 'Order not found.' using errcode = 'P0002';
  end if;

  if v_current::text = p_new_status then
    return query select o.id, o.order_number, o.status::text, o.updated_at from public.orders o where o.id = p_order_id;
    return;
  end if;
  if not ((v_current = 'Pending' and p_new_status = 'Preparing') or (v_current = 'Preparing' and p_new_status = 'Ready')) then
    raise exception 'Orders move forward only: Pending, Preparing, then Ready.' using errcode = '22023';
  end if;

  update public.orders
  set
    status = p_new_status::public.order_status,
    preparing_at = case when p_new_status = 'Preparing' then now() else preparing_at end,
    ready_at = case when p_new_status = 'Ready' then now() else ready_at end
  where id = p_order_id;

  return query select o.id, o.order_number, o.status::text, o.updated_at from public.orders o where o.id = p_order_id;
end;
$$;

revoke all on function public.admin_update_order_status(uuid, text) from public, anon;
grant execute on function public.admin_update_order_status(uuid, text) to authenticated;

create or replace function public.get_admin_dashboard_stats()
returns table (
  total_orders_today bigint,
  total_revenue_today numeric,
  pending_orders bigint,
  total_menu_items bigint,
  unavailable_menu_items bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_day_start timestamptz;
begin
  if not public.is_admin() then
    raise exception 'Admin permission is required.' using errcode = '42501';
  end if;
  v_day_start := date_trunc('day', now() at time zone 'Asia/Karachi') at time zone 'Asia/Karachi';

  return query
  select
    count(*) filter (where o.created_at >= v_day_start),
    coalesce(sum(o.total) filter (where o.created_at >= v_day_start), 0),
    count(*) filter (where o.status = 'Pending'),
    (select count(*) from public.menu_items),
    (select count(*) from public.menu_items where available = false)
  from public.orders o;
end;
$$;

revoke all on function public.get_admin_dashboard_stats() from public, anon;
grant execute on function public.get_admin_dashboard_stats() to authenticated;

